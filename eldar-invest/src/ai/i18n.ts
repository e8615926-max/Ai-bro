const DICTS: Record<AiLang, Dict> = { en, ru };

export function tr(lang: AiLang, key: string, params: Record<string, string | number> = {}): string {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

