/**
 * ELDAR INVEST market simulator
 * ------------------------------------------------------------------
 * Every price in the app is produced here. Nothing is fetched from a real
 * exchange. The simulator is a pure function of (symbol, time):
 *
 *   - Daily closes come from a seeded log-normal random walk (with mild mean
 *     reversion and rare jumps) that starts on 2019-01-01.
 *   - Within each day, prices follow a seeded Brownian bridge between the
 *     previous close and that day's close, at one-minute resolution.
 *
 * Because the output only depends on the symbol and the timestamp, prices
 * are consistent across reloads, devices and users — which keeps virtual
 * portfolio values and history stable — while still "moving" in real time.
 */
import { ASSETS, getAsset, type Asset } from '@/data/assets';
import { hashString, seeded } from './random';
import { DAY, MINUTE, dayEnd, dayNumber, dayStart } from './time';

export const DEMO_DATA_NOTICE =
  'Simulated demo data. Prices, charts and statistics are generated by ELDAR INVEST and are not real market quotes.';

const EPOCH_DAY = Math.floor(Date.UTC(2019, 0, 1) / DAY);
const ANCHOR_DAY = Math.floor(Date.UTC(2026, 9, 1) / DAY);
const MIN_PER_DAY = 1440;
const DT = 1 / 365; // the simulated market trades every day

interface DailyPath {
  logs: number[]; // index 0 = EPOCH_DAY
  offset: number;
  gen: { rand: () => number; normal: () => number };
  asset: Asset;
}

const dailyCache = new Map<string, DailyPath>();

function stepDaily(p: DailyPath) {
  const { asset, gen, logs } = p;
  const i = logs.length - 1;
  const x = logs[i];
  const trend = (asset.drift - 0.5 * asset.vol * asset.vol) * DT;
  const target = (asset.drift - 0.5 * asset.vol * asset.vol) * (i * DT);
  let shock = asset.vol * Math.sqrt(DT) * gen.normal();
  if (gen.rand() < 0.012) shock += asset.vol * Math.sqrt(DT) * 3 * gen.normal(); // rare jump
  const reversion = -0.004 * (x - target);
  logs.push(x + trend + shock + reversion);
}

function dailyPath(asset: Asset, uptoDay: number): DailyPath {
  let p = dailyCache.get(asset.symbol);
  if (!p) {
    p = { logs: [0], offset: 0, gen: seeded('daily:' + asset.symbol), asset };
    dailyCache.set(asset.symbol, p);
    while (p.logs.length - 1 < ANCHOR_DAY - EPOCH_DAY) stepDaily(p);
    p.offset = Math.log(asset.refPrice) - p.logs[ANCHOR_DAY - EPOCH_DAY];
  }
  while (p.logs.length - 1 < uptoDay - EPOCH_DAY) stepDaily(p);
  return p;
}

function requireAsset(symbol: string): Asset {
  const a = getAsset(symbol);
  if (!a) throw new Error(`Unknown symbol: ${symbol}`);
  return a;
}

/** Simulated closing price for a calendar day number. */
export function closeOn(symbol: string, day: number): number {
  const asset = requireAsset(symbol);
  const d = Math.max(day, EPOCH_DAY);
  const p = dailyPath(asset, d);
  return Math.exp(p.logs[d - EPOCH_DAY] + p.offset);
}

/* ---------------------------- Intraday bridge ---------------------------- */

const bridgeCache = new Map<string, Float64Array>();
const BRIDGE_CACHE_LIMIT = 600;

function bridge(symbol: string, day: number): Float64Array {
  const key = symbol + ':' + day;
  const hit = bridgeCache.get(key);
  if (hit) {
    bridgeCache.delete(key);
    bridgeCache.set(key, hit);
    return hit;
  }
  const asset = requireAsset(symbol);
  const open = Math.log(closeOn(symbol, day - 1));
  const close = Math.log(closeOn(symbol, day));
  const { normal } = seeded('intraday:' + key);
  const sd = asset.vol * Math.sqrt(DT / MIN_PER_DAY);
  const w = new Float64Array(MIN_PER_DAY + 1);
  for (let i = 1; i <= MIN_PER_DAY; i++) w[i] = w[i - 1] + sd * normal();
  const out = new Float64Array(MIN_PER_DAY + 1);
  const wn = w[MIN_PER_DAY];
  for (let i = 0; i <= MIN_PER_DAY; i++) {
    const f = i / MIN_PER_DAY;
    out[i] = Math.exp(open + f * (close - open) + (w[i] - f * wn));
  }
  bridgeCache.set(key, out);
  if (bridgeCache.size > BRIDGE_CACHE_LIMIT) {
    const first = bridgeCache.keys().next().value;
    if (first !== undefined) bridgeCache.delete(first);
  }
  return out;
}

/** Simulated price of `symbol` at timestamp `t` (ms). */
export function priceAt(symbol: string, t: number): number {
  const day = dayNumber(t);
  if (day <= EPOCH_DAY) return closeOn(symbol, EPOCH_DAY);
  const s = dayStart(day);
  const len = dayEnd(day) - s; // 23–25h around DST changes
  const pos = Math.min(Math.max(((t - s) / len) * MIN_PER_DAY, 0), MIN_PER_DAY);
  const i = Math.min(Math.floor(pos), MIN_PER_DAY - 1);
  const m = pos - i;
  const b = bridge(symbol, day);
  const base = b[i] + (b[i + 1] - b[i]) * m;
  // Smooth sub-minute movement that vanishes on minute boundaries, so live
  // quotes tick between chart points while staying deterministic.
  const asset = requireAsset(symbol);
  const amp = asset.vol * Math.sqrt(DT / MIN_PER_DAY) * 0.6;
  const phase = (hashString(symbol + i) % 1000) / 159.15;
  const jitter = amp * Math.sin(Math.PI * m) * Math.sin(6 * Math.PI * m + phase);
  return base * (1 + jitter);
}

/* --------------------------------- Quotes -------------------------------- */

export interface Quote {
  symbol: string;
  price: number;
  prevClose: number;
  change: number;
  changePct: number;
}

export function getQuote(symbol: string, now: number): Quote {
  const price = priceAt(symbol, now);
  const prevClose = closeOn(symbol, dayNumber(now) - 1);
  const change = price - prevClose;
  return { symbol, price, prevClose, change, changePct: change / prevClose };
}

export function getAllQuotes(now: number): Record<string, Quote> {
  const out: Record<string, Quote> = {};
  for (const a of ASSETS) out[a.symbol] = getQuote(a.symbol, now);
  return out;
}

export interface DayStats {
  open: number;
  high: number;
  low: number;
  volume: number;
  high52: number;
  low52: number;
  avgVolume: number;
}

export function getDayStats(symbol: string, now: number): DayStats {
  const asset = requireAsset(symbol);
  const day = dayNumber(now);
  const b = bridge(symbol, day);
  const s = dayStart(day);
  const idx = Math.min(MIN_PER_DAY, Math.floor(((now - s) / (dayEnd(day) - s)) * MIN_PER_DAY));
  const current = priceAt(symbol, now);
  let high = current;
  let low = current;
  for (let i = 0; i <= idx; i++) {
    if (b[i] > high) high = b[i];
    if (b[i] < low) low = b[i];
  }
  let high52 = high;
  let low52 = low;
  for (let d = day - 365; d < day; d++) {
    const c = closeOn(symbol, d);
    if (c > high52) high52 = c;
    if (c < low52) low52 = c;
  }
  const baseVolume = 2_000_000 + (hashString('vol:' + symbol) % 60_000_000) * (asset.type === 'etf' ? 0.8 : 1);
  const elapsed = Math.max(0.01, idx / MIN_PER_DAY);
  const { rand } = seeded('volume:' + symbol + ':' + day);
  const dayFactor = 0.7 + rand() * 0.6;
  return { open: b[0], high, low, volume: baseVolume * dayFactor * elapsed, high52, low52, avgVolume: baseVolume };
}

/* --------------------------------- Series -------------------------------- */

export type Range = '1D' | '1W' | '1M' | '3M' | '1Y' | '5Y';
export const RANGES: Range[] = ['1D', '1W', '1M', '3M', '1Y', '5Y'];

export interface Point {
  t: number;
  v: number;
}

interface GridSpec {
  start: number;
  /** Intraday step in ms, or 'daily' for one point per day close. */
  step: number | 'daily';
  dayStride?: number;
}

export function rangeSpec(range: Range, now: number): GridSpec {
  switch (range) {
    case '1D':
      return { start: dayStart(dayNumber(now)), step: 5 * MINUTE };
    case '1W':
      return { start: now - 7 * DAY, step: 30 * MINUTE };
    case '1M':
      return { start: now - 30 * DAY, step: 3 * 60 * MINUTE };
    case '3M':
      return { start: dayStart(dayNumber(now) - 91), step: 'daily' };
    case '1Y':
      return { start: dayStart(dayNumber(now) - 365), step: 'daily' };
    case '5Y':
      return { start: dayStart(dayNumber(now) - 365 * 5), step: 'daily', dayStride: 2 };
  }
}

/**
 * Timestamps for a chart range. Daily grids use each day's close time;
 * the final point is always `now`.
 */
export function timeGrid(range: Range, now: number, notBefore = -Infinity): number[] {
  const spec = rangeSpec(range, now);
  const start = Math.max(spec.start, notBefore);
  const out: number[] = [];
  if (spec.step === 'daily') {
    const stride = spec.dayStride ?? 1;
    const today = dayNumber(now);
    for (let d = dayNumber(start); d < today; d += stride) {
      const t = dayEnd(d) - 1;
      if (t >= start) out.push(t);
    }
  } else {
    const step = spec.step;
    for (let t = Math.ceil(start / step) * step; t < now; t += step) out.push(t);
  }
  if (out.length === 0 || out[0] > start) out.unshift(start);
  if (out[out.length - 1] !== now) out.push(now);
  return out;
}

/**
 * Returns a price function optimised for a range: daily ranges read the
 * pre-computed daily closes for past days instead of intraday paths.
 */
export function pricerFor(range: Range, now: number): (symbol: string, t: number) => number {
  if (rangeSpec(range, now).step !== 'daily') return priceAt;
  const today = dayNumber(now);
  return (symbol, t) => {
    const d = dayNumber(t);
    if (d >= today) return priceAt(symbol, t);
    if (t === dayStart(d)) return closeOn(symbol, d - 1);
    if (t === dayEnd(d) - 1) return closeOn(symbol, d);
    return priceAt(symbol, t);
  };
}

export function assetSeries(symbol: string, range: Range, now: number): Point[] {
  const price = pricerFor(range, now);
  return timeGrid(range, now).map((t) => ({ t, v: price(symbol, t) }));
}

/** Percentage change across a range for an asset. */
export function rangeChange(symbol: string, range: Range, now: number) {
  const series = assetSeries(symbol, range, now);
  const first = range === '1D' ? closeOn(symbol, dayNumber(now) - 1) : series[0].v;
  const last = series[series.length - 1].v;
  return { first, last, change: last - first, changePct: (last - first) / first };
}

/** Compact series for sparklines (last 24h, ~48 points). */
export function sparkline(symbol: string, now: number): number[] {
  const out: number[] = [];
  const step = 30 * MINUTE;
  const start = Math.floor((now - DAY) / step) * step;
  for (let t = start; t < now; t += step) out.push(priceAt(symbol, t));
  out.push(priceAt(symbol, now));
  return out;
}

export function isKnownSymbol(symbol: string): boolean {
  return !!getAsset(symbol);
}
