import type { ReactNode } from 'react';
import { FlaskConical, TrendingDown, TrendingUp } from 'lucide-react';
import { cn } from '@/lib/cn';
import { percent, money } from '@/lib/format';

export function Badge({ children, tone = 'neutral', className }: { children: ReactNode; tone?: 'neutral' | 'brand' | 'gain' | 'loss' | 'warn'; className?: string }) {
  const tones = {
    neutral: 'bg-surface-2 text-ink-2',
    brand: 'bg-brand-soft text-brand-strong',
    gain: 'bg-gain-soft text-gain',
    loss: 'bg-loss-soft text-loss',
    warn: 'bg-warn-soft text-warn',
  };
  return <span className={cn('inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-[11px] font-semibold', tones[tone], className)}>{children}</span>;
}

/** Explicit marker shown next to every simulated figure. */
export function DemoBadge({ className, label = 'Demo data' }: { className?: string; label?: string }) {
  return (
    <span
      className={cn('inline-flex items-center gap-1 rounded-full border border-warn/30 bg-warn-soft px-2 py-0.5 text-[10.5px] font-semibold uppercase tracking-wide text-warn', className)}
      title="Simulated prices generated by ELDAR INVEST — not real market data"
    >
      <FlaskConical size={11} strokeWidth={2.5} />
      {label}
    </span>
  );
}

export function Change({ value, pct, className, pill = false, icon = false, hidden = false }: { value?: number; pct: number; className?: string; pill?: boolean; icon?: boolean; hidden?: boolean }) {
  const up = pct > 0.000001;
  const down = pct < -0.000001;
  const color = up ? 'text-gain' : down ? 'text-loss' : 'text-ink-3';
  const bg = up ? 'bg-gain-soft' : down ? 'bg-loss-soft' : 'bg-surface-2';
  const Icon = down ? TrendingDown : TrendingUp;
  return (
    <span className={cn('num inline-flex items-center gap-1 font-semibold', color, pill && cn(bg, 'rounded-lg px-2 py-0.5'), className)}>
      {icon && (up || down) && <Icon size={14} strokeWidth={2.5} />}
      {value !== undefined && <span>{hidden ? '••••' : money(value, { sign: true })}</span>}
      <span>{value !== undefined ? `(${percent(pct)})` : percent(pct)}</span>
    </span>
  );
}

export function Skeleton({ className }: { className?: string }) {
  return <div className={cn('skeleton', className)} aria-hidden="true" />;
}

export function EmptyState({ icon, title, body, action, className }: { icon: ReactNode; title: string; body: string; action?: ReactNode; className?: string }) {
  return (
    <div className={cn('flex flex-col items-center px-6 py-12 text-center', className)}>
      <div className="mb-4 flex h-14 w-14 items-center justify-center rounded-2xl bg-brand-soft text-brand">{icon}</div>
      <h3 className="text-[15px] font-semibold">{title}</h3>
      <p className="mt-1 max-w-xs text-sm text-ink-2">{body}</p>
      {action && <div className="mt-5">{action}</div>}
    </div>
  );
}

export function Avatar({ name, hue, size = 40, className }: { name: string; hue: number; size?: number; className?: string }) {
  const initials = name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((p) => p[0]!.toUpperCase())
    .join('');
  return (
    <span
      className={cn('inline-flex shrink-0 items-center justify-center rounded-full font-semibold text-white', className)}
      style={{ width: size, height: size, fontSize: size * 0.38, background: `linear-gradient(135deg, hsl(${hue} 62% 52%), hsl(${(hue + 40) % 360} 60% 40%))` }}
      aria-hidden="true"
    >
      {initials || '?'}
    </span>
  );
}

export function Stat({ label, value, sub, className }: { label: string; value: ReactNode; sub?: ReactNode; className?: string }) {
  return (
    <div className={className}>
      <div className="text-[12px] font-medium text-ink-3">{label}</div>
      <div className="num mt-1 text-[15px] font-semibold text-ink">{value}</div>
      {sub && <div className="mt-0.5 text-[12px]">{sub}</div>}
    </div>
  );
}
