M_SK = (46, 52, 40, 255)


def mutant(c, t=0.0, var=0, walk=0.0):
    """Сгорбленный мутант, высота ~1000. Возвращает лок. координаты глаз."""
    s = math.sin(walk)
    sk = (M_SK[0] + var * 6, M_SK[1] - var * 4, M_SK[2] + var * 4, 255)
    dk = (sk[0] - 16, sk[1] - 16, sk[2] - 14, 255)
    # ноги
    c.line([(-60, 560), (-90 + s * 40, 780), (-70 + s * 60, 1000)], dk, 70, smooth=True)
    c.line([(60, 560), (90 - s * 40, 780), (70 - s * 60, 1000)], dk, 70, smooth=True)
    # туловище (горб)
    c.poly([(-150, 260), (-60, 150), (80, 140), (170, 240), (150, 480), (80, 600), (-80, 600), (-150, 470)], sk, smooth=True)
    if var % 2 == 1:
        c.ell((40, 120, 190, 270), dk)   # нарост
    for k in range(4):
        c.line([(-90 + k * 40, 300), (-80 + k * 40, 420)], dk, 10)
    # руки длинные
    c.line([(-130, 260), (-220 + s * 40, 560), (-200 + s * 80, 880)], sk, 60, smooth=True)
    c.line([(140, 250), (230 - s * 40, 560), (210 - s * 80, 880)], sk, 60, smooth=True)
    for hx in (-200 + s * 80, 210 - s * 80):
        for k in range(3):
            c.line([(hx, 880), (hx - 30 + k * 30, 960)], (200, 190, 170, 255), 10)
    if var == 2:
        c.line([(100, 300), (260, 380), (300, 560)], sk, 44, smooth=True)   # третья рука
    # голова, опущенная вперёд
    c.ell((-80, 40, 80, 220), sk)
    c.poly([(-50, 170), (50, 170), (30, 230), (-30, 230)], (30, 10, 10, 255))
    for k in range(5):
        c.poly([(-40 + k * 20, 172), (-30 + k * 20, 172), (-35 + k * 20, 196)], (230, 220, 200, 255))
    return [(-34, 120), (34, 120)]


def spider(c, t=0.0, spread=0.0):
    """Человек-паук-мутант с обводкой. (0,0) — центр тела. Возвращает лок. координаты глаз."""
    from human import limb
    OL = (0, 0, 0, 255)
    body = (14, 12, 16, 255)       # паучьи части — чёрные
    leg = (22, 20, 26, 255)
    skin = (126, 142, 122, 255)
    legs = []
    for side in (-1, 1):
        for i in range(4):
            a0 = math.radians(-60 + i * 38)
            w = math.sin(t * 18 + i * 1.3 + side) * 0.14
            l1 = 300 + spread * 220
            j0 = (side * 90, -10 + i * 34)
            j1 = (side * math.cos(a0 + w) * l1 * 0.95, -abs(math.sin(a0 + w)) * 170 - 230 + i * 64)
            j2 = (side * (math.cos(a0 + w) * l1 * 1.65 + 120), 260 + i * 74 - spread * 220 * (1 - i / 3))
            legs.append((j0, j1, j2, side))
    # обводка всех ног, затем заливка
    for j0, j1, j2, side in legs:
        limb(c, j0, j1, 62, 46, OL)
        limb(c, j1, j2, 46, 18, OL)
    for j0, j1, j2, side in legs:
        limb(c, j0, j1, 48, 34, leg)
        limb(c, j1, j2, 34, 10, leg)
        c.circ(j1[0], j1[1], 30, OL)
        c.circ(j1[0], j1[1], 22, (40, 38, 46, 255))
        for q in range(5):   # щетинки
            u = 0.2 + q * 0.15
            px, py = j1[0] + (j2[0] - j1[0]) * u, j1[1] + (j2[1] - j1[1]) * u
            c.line([(px, py), (px + side * 16, py - 14)], OL, 3)
        c.line([j2, (j2[0] + side * 22, j2[1] + 64)], (220, 210, 200, 255), 12)
    # брюшко
    c.ell((-214, -74, 214, 334), OL)
    c.ell((-200, -60, 200, 320), body)
    c.ell((-150, -30, 120, 160), (30, 28, 34, 255))
    c.poly([(0, 60), (44, 130), (0, 200), (-44, 130)], (210, 20, 20, 255))
    c.poly([(0, 210), (30, 250), (0, 290), (-30, 250)], (210, 20, 20, 255))
    for k in range(6):
        c.arc((-170 + k * 10, -40 + k * 30, 170 - k * 10, 300 - k * 10), 200, 340, (44, 42, 50, 255), 4)
    # человеческий торс
    torso = [(-112, -20), (-132, -240), (-62, -302), (62, -302), (132, -240), (112, -20)]
    c.poly([(x * 1.08, y * 1.04 - 4) for x, y in torso], OL, smooth=True)
    c.poly(torso, skin, smooth=True)
    for k in range(3):
        c.line([(-70, -200 + k * 50), (70, -200 + k * 50)], (90, 104, 90, 255), 6)
    for k in range(5):
        c.line([(-90 + k * 40, -60), (-70 + k * 40, -160), (-86 + k * 40, -230)], (70, 40, 80, 255), 4, smooth=True)
    sw = math.sin(t * 10) * 30
    for side in (-1, 1):
        p0, p1, p2 = (side * 120, -260), (side * (270 + sw), -150), (side * 210, -370 - spread * 110)
        limb(c, p0, p1, 64, 56, OL); limb(c, p1, p2, 56, 46, OL)
        limb(c, p0, p1, 50, 44, skin); limb(c, p1, p2, 44, 36, skin)
        for k in range(3):
            c.line([p2, (side * (180 + k * 34), -450 - spread * 110)], OL, 14)
            c.line([p2, (side * (180 + k * 34), -446 - spread * 110)], (230, 220, 200, 255), 8)
    c.ell((-100, -480, 100, -282), OL)
    c.ell((-90, -470, 90, -290), skin)
    for k in range(4):   # вены
        c.line([(-60 + k * 40, -460), (-50 + k * 40, -420)], (80, 100, 80, 255), 3)
    c.poly([(-56, -346), (56, -346), (38, -292), (-38, -292)], (40, 6, 10, 255))
    for side in (-1, 1):
        c.poly([(side * 36, -346), (side * 18, -346), (side * 28, -292)], (240, 230, 210, 255))
        c.poly([(side * 12, -346), (side * 4, -346), (side * 8, -316)], (240, 230, 210, 255))
    eyes = [(-40, -410), (40, -410), (-62, -380), (62, -380), (-20, -440), (20, -440)]
    for ex, ey in eyes:
        c.circ(ex, ey, 17, OL)
        c.circ(ex, ey, 13, (90, 0, 0, 255))
    return eyes
