def elli_back(c, t=0.0, walk=0.0, run=False, mic=True):
    """walk — фаза шага (рад). run — бег."""
    amp = 1.7 if run else 1.0
    s = math.sin(walk)
    bob = -abs(math.cos(walk)) * 18 * amp
    c = c.sub(0, bob, 1.0)
    # ноги (уходит от камеры: одна нога приподнята)
    for side, ph in ((-1, s), (1, -s)):
        lift = max(0, ph) * 90 * amp
        x = side * 52
        c.rect((x - 46, 1080, x + 46, 1620 - lift), E_LEG, r=20)
        c.rect((x - 46, 1560 - lift, x + 46, 1700 - lift * 1.1), E_BOOT, r=24)
        if lift > 10:
            c.rect((x - 40, 1640 - lift * 1.1, x + 40, 1700 - lift * 1.1), (60, 50, 50, 255), r=10)
    coat = [(-155, 290), (-120, 250), (-40, 238), (40, 238), (120, 250), (155, 290), (165, 620), (158, 1000), (140, 1090), (-140, 1090), (-158, 1000), (-165, 620)]
    c.poly(coat, E_COAT, smooth=True)
    c.rect((-160, 620, 160, 664), E_COAT_D)
    c.line([(0, 700), (0, 1090)], E_COAT_D, 8)
    sw = s * 40 * amp
    for side in (-1, 1):
        if run:
            c.line([(side * 140, 300), (side * (230 + sw * side), 520), (side * 190, 700 - sw * side * 3)], E_COAT, 74, smooth=True)
        else:
            c.line([(side * 140, 300), (side * 176, 620 + sw * side), (side * 166, 820 + sw * side)], E_COAT, 74, smooth=True)
    if mic and not run:
        c.ell((-210, 800, -140, 870), E_SKIN)
    c.rect((-30, 170, 30, 260), (110, 78, 66, 255))
    c.ell((-90, -10, 90, 200), E_HAIR)
    c.line([(0, 120), (6 + s * 10, 260), (-4 + s * 16, 380)], E_HAIR, 46, smooth=True)   # хвост
    c.circ(0, 120, 26, (40, 24, 20, 255))


